let currentLang = localStorage.getItem('siteLang') || 'am';

// Global helper to safely render old Google Drive image URLs
window.getSafeImageUrl = function(url) {
    if (!url) return '';
    const driveMatch = url.match(/id=([^&]+)/) || url.match(/d\/([a-zA-Z0-9_-]+)/);
    if (url.includes('lh3.googleusercontent.com/d/') && driveMatch) {
        return `https://drive.google.com/uc?export=view&id=${driveMatch[1]}`;
    }
    return url;
};

// Expose switchLanguage globally so existing buttons can use it, or override changeLanguage
window.changeLanguage = function(lang) {
    if (lang === currentLang && document.body.dataset.langTranslated) return; // Prevent double translation
    currentLang = lang;
    localStorage.setItem('siteLang', lang);
    document.body.dataset.langTranslated = 'true';
    
    // Update the existing buttons using the original function if it exists
    if (typeof window.updateLangButtons === 'function') {
        window.updateLangButtons(lang);
    }
    
    translateDOM(lang);
};

function initTranslations() {
    // Perform initial translation if needed
    if (currentLang === 'en') {
        translateDOM('en');
    }
    
    // Override the existing window.changeLanguage from the HTML files
    // so the existing navbar button calls our new logic.
    // The original script sets it on window, so we just overwrite it.
    
    // Observer for dynamically added content (like courses loading)
    const observer = new MutationObserver((mutations) => {
        if (currentLang === 'en') {
            mutations.forEach(mutation => {
                if (mutation.addedNodes.length > 0) {
                    mutation.addedNodes.forEach(node => {
                        if (node.nodeType === 1) { // Element node
                            translateDOMNode('en', node);
                        } else if (node.nodeType === 3) { // Text node
                            translateTextNode('en', node);
                        }
                    });
                }
            });
        }
    });
    
    observer.observe(document.body, { childList: true, subtree: true });
}

function translateDOM(lang) {
    translateDOMNode(lang, document.body);
}

function translateDOMNode(lang, rootNode) {
    if (!rootNode) return;
    const walker = document.createTreeWalker(rootNode, NodeFilter.SHOW_TEXT, null, false);
    let node;
    const nodesToTranslate = [];
    while (node = walker.nextNode()) {
        nodesToTranslate.push(node);
    }
    nodesToTranslate.forEach(n => translateTextNode(lang, n));
}

function translateTextNode(lang, node) {
    // Ignore script and style content
    if (node.parentNode && (node.parentNode.tagName === 'SCRIPT' || node.parentNode.tagName === 'STYLE' || node.parentNode.tagName === 'NOSCRIPT')) return;
    if (node.parentNode && node.parentNode.classList && node.parentNode.classList.contains('notranslate')) return;
    
    const originalText = node._originalText || node.nodeValue;
    const cleanText = originalText.replace(/\s+/g, ' ').trim();
    
    if (cleanText === '') return;

    if (lang === 'en') {
        if (amharicToEnglish[cleanText]) {
            if (!node._originalText) node._originalText = node.nodeValue;
            
            // Preserve leading/trailing whitespace
            const leadingMatch = originalText.match(/^\s*/);
            const trailingMatch = originalText.match(/\s*$/);
            const leading = leadingMatch ? leadingMatch[0] : '';
            const trailing = trailingMatch ? trailingMatch[0] : '';
            
            node.nodeValue = leading + amharicToEnglish[cleanText] + trailing;
        }
    } else {
        // Revert to Amharic
        if (node._originalText) {
            node.nodeValue = node._originalText;
        }
    }
}

// Initialize when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initTranslations);
} else {
    initTranslations();
}
